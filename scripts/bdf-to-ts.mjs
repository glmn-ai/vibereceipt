// Converts Spleen BDF fonts (BSD-2-Clause, https://github.com/fcambus/spleen)
// into a TypeScript module with the glyphs vibereceipt draws.
// Usage: node scripts/bdf-to-ts.mjs <spleen-8x16.bdf> <spleen-16x32.bdf> > src/png/fontData.ts
import { readFileSync } from 'node:fs'

const EXTRA = [0xb7, 0xd7, 0x2014, 0x2212, 0x2019, 0x2022, 0x2588, 0x258c, 0x2590, 0x2591, 0x2592, 0x2605, 0x2665]
const wanted = new Set([...Array.from({ length: 95 }, (_, i) => 32 + i), ...EXTRA])

function parse(path) {
  const text = readFileSync(path, 'utf8')
  const [w, h, , descent] = /FONTBOUNDINGBOX (\d+) (\d+) (-?\d+) (-?\d+)/.exec(text).slice(1).map(Number)
  const glyphs = {}
  for (const block of text.split('STARTCHAR').slice(1)) {
    const code = Number(/ENCODING (\d+)/.exec(block)[1])
    if (!wanted.has(code)) continue
    const [bw, bh, bx, by] = /BBX (\d+) (\d+) (-?\d+) (-?\d+)/.exec(block).slice(1).map(Number)
    const rows = /BITMAP\s+([\s\S]*?)ENDCHAR/.exec(block)[1].trim().split(/\s+/)
    // Place the glyph's bbox into the full cell (bottom = descent line).
    const cell = Array(h).fill(0n)
    const top = h - (by - descent) - bh
    const bytes = Math.ceil(bw / 8)
    rows.forEach((hex, i) => {
      const value = BigInt('0x' + hex) >> BigInt(bytes * 8 - bw)
      const y = top + i
      if (y >= 0 && y < h) cell[y] = value << BigInt(w - bw - bx)
    })
    const digits = Math.ceil(w / 4)
    glyphs[code] = cell.map((v) => v.toString(16).padStart(digits, '0')).join('')
  }
  return { w, h, glyphs }
}

const fonts = process.argv.slice(2).map(parse)
const out = [
  '// GENERATED by scripts/bdf-to-ts.mjs from Spleen 2.2.0 — do not edit.',
  '// Spleen (c) 2018-2026 Frederic Cambus, BSD-2-Clause — see fonts/LICENSE-spleen.',
  '// Each glyph: the cell\'s rows, top to bottom, as fixed-width hex (MSB = leftmost pixel).',
  ''
]
for (const f of fonts) {
  out.push(`export const SPLEEN_${f.w}X${f.h} = {`, `  width: ${f.w},`, `  height: ${f.h},`, '  glyphs: {')
  for (const [code, hex] of Object.entries(f.glyphs)) out.push(`    ${code}: '${hex}',`)
  out.push('  } as Record<number, string>', '}', '')
}
process.stdout.write(out.join('\n'))
